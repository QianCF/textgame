  function 更新农场显示文本() {
    const 农场数据 = Game.状态.农场数据;
    if (!农场数据) return;
    
    const 季节名称 = 获取季节名称(农场数据.时间.季);
    const 时间描述 = `第${农场数据.时间.年}年${季节名称}季第${农场数据.时间.日}天 ${农场数据.时间.时}:00`;
    
    // 统计土地信息（递归获取所有土地，包括收纳袋中的）
    const 土地物品列表 = 递归获取所有土地(Game.状态.物品);
    
    const 空闲土地 = 土地物品列表.filter(l => l.状态 === '空闲').length;
    const 生长中土地 = 土地物品列表.filter(l => l.状态 === '生长中').length;
    const 可收获土地 = 土地物品列表.filter(l => l.状态 === '可收获').length;
    
    // 更新农场的显示文本
    农场数据.显示文本 = `你的农场\n时间：${时间描述}\n土地：${土地物品列表.length}块（空闲:${空闲土地} 生长中:${生长中土地} 可收获:${可收获土地}）`;
    
    // 同时更新地点类的显示文本
    农场.显示的文本 = 农场数据.显示文本;
  }

  // 时间流逝系统（每10秒游戏时间推进1小时）
  function 时间流逝检测() {
    if (!Game.状态.农场数据 || !Game.状态.农场数据.时间流逝中) {
      return;
    }
    
    const 现在 = Date.now();
    const 上次更新 = Game.状态.农场数据.最后更新时间 || 现在;
    const 经过秒数 = (现在 - 上次更新) / 1000;
    
    // 5秒游戏时间 = 1小时
    if (经过秒数 >= 5) {
      推进时间(1);
      Game.状态.农场数据.最后更新时间 = 现在;
    }
    
    // 更新土地物品状态
    更新所有土地物品状态();
    
    // 更新显示
    更新农场显示文本();
    更新状态显示();
    Game.渲染();
  }

  // 更新所有土地物品的状态
  function 更新所有土地物品状态() {
    if (!Game.状态.农场数据) return;
    
    const 当前时间小时数 = 时间到总小时数(Game.状态.农场数据.时间);
    const 当前季节 = Game.状态.农场数据.时间.季;
    
    // 递归获取所有土地（包括收纳袋中的）
    const 所有土地 = 递归获取所有土地(Game.状态.物品);
    
    // 检查是否发生了时间变化
    if (当前时间小时数 !== 上次时间小时数) {
      const 时间差 = 当前时间小时数 - 上次时间小时数;
      
      if (时间差 > 0) {
        // 时间向前推进了，更新所有土地的生长状态
        所有土地.forEach(item => {
          if (item.状态 === '生长中' && item.作物) {
            // 检查当前季节是否适合作物生长
            const 是否生长季 = 检查是否生长季(item.作物, 当前季节);
            
            if (是否生长季) {
              // 只在生长季节增加生长时间
              item.已生长小时数 += 时间差;
              
              const 作物配置 = 作物数据[item.作物];
              if (作物配置) {
                const 所需小时数 = 作物配置.生长时间 * 24;
                
                // 更新进度
                item.进度 = Math.min(item.已生长小时数 / 所需小时数, 1);
                
                // 检查是否成熟
                if (item.已生长小时数 >= 所需小时数 && item.状态 !== '可收获') {
                  item.状态 = '可收获';
                  item.能否使用 = true;
                  Game.消息队列添加(`${item.作物} 已经成熟，可以收获了！`, "农场通知");
                }
              }
            }
          }
        });
      }
      
      上次时间小时数 = 当前时间小时数;
    }
    
    // 更新所有土地的显示状态
    所有土地.forEach(item => {
      item.更新显示状态(item);
    });
  }

  function 暂停时间() {
    Game.状态.农场数据.时间流逝中 = false;
    Game.消息队列添加("农场时间已暂停", "时间管理");
    更新状态显示();
  }

  function 恢复时间() {
    Game.状态.农场数据.时间流逝中 = true;
    Game.状态.农场数据.最后更新时间 = Date.now();
    Game.消息队列添加("农场时间已恢复", "时间管理");
    更新状态显示();
  }

  function 推进时间(小时数) {
    const 当前总小时数 = 时间到总小时数(Game.状态.农场数据.时间);
    const 新总小时数 = 当前总小时数 + 小时数;
    Game.状态.农场数据.时间 = 总小时数到时间(新总小时数);
    
    // 检查是否到了新的一天
    const 原时间 = 总小时数到时间(当前总小时数);
    const 新时间 = Game.状态.农场数据.时间;
    
    // 如果天数变化了，生成新任务
    if (新时间.日 !== 原时间.日) {
      生成日常任务();
    }
  }

  function 更新状态显示() {
    const 农场 = Game.状态.农场数据;
    if (!农场) return;
    
    // 确保状态栏存在
    if (!Game.状态.其他状态栏) {
      Game.状态.其他状态栏 = [];
    }
    
    // 更新或添加农场时间
    const 时间索引 = Game.状态.其他状态栏.findIndex(item => item.名字 === "农场时间");
    if (时间索引 !== -1) {
      Game.状态.其他状态栏[时间索引].值 = 农场.时间流逝中 ? "流动中" : "已暂停";
    } else {
      Game.状态.其他状态栏.push({ 名字: "农场时间", 值: 农场.时间流逝中 ? "流动中" : "已暂停" });
    }
    
    // 更新或添加经验值
    const 经验索引 = Game.状态.其他状态栏.findIndex(item => item.名字 === "经验值");
    if (经验索引 !== -1) {
      Game.状态.其他状态栏[经验索引].值 = 农场.经验值;
    } else {
      Game.状态.其他状态栏.push({ 名字: "经验值", 值: 农场.经验值 });
    }
    
    // 如果当前在农场，则更新耕种土地状态
    if (Game.状态.所在地点 === "农场") {
      const 土地物品列表 = 递归获取所有土地(Game.状态.物品);
      const 耕种土地 = 土地物品列表.filter(l => l.状态 === '生长中' || l.状态 === '可收获').length;
      
      const 耕种索引 = Game.状态.其他状态栏.findIndex(item => item.名字 === "耕种土地");
      if (耕种索引 !== -1) {
        Game.状态.其他状态栏[耕种索引].值 = `${耕种土地}/${土地物品列表.length}`;
      } else {
        Game.状态.其他状态栏.push({ 名字: "耕种土地", 值: `${耕种土地}/${土地物品列表.length}` });
      }
    } else {
      // 如果不在农场，移除只与农场相关的状态
      const 需要移除的状态 = ["耕种土地"];
      Game.状态.其他状态栏 = Game.状态.其他状态栏.filter(
        item => !需要移除的状态.includes(item.名字)
      );
    }
  }

  function 生成日常任务() {
    Game.状态.农场数据.任务 = [];
    
    const 任务类型 = [
      { 类型: '种植', 作物: '小麦', 数量: 3, 奖励: { 经验: 10, 金币: 15 * 4 } },
      { 类型: '种植', 作物: '胡萝卜', 数量: 3, 奖励: { 经验: 10, 金币: 19 * 4 } },
      { 类型: '种植', 作物: '土豆', 数量: 3, 奖励: { 经验: 10, 金币: 17 * 4 } },
      { 类型: '收获', 作物: '胡萝卜', 数量: 2, 奖励: { 经验: 15, 金币: 8 * 4 } },
      { 类型: '收获', 作物: '土豆', 数量: 2, 奖励: { 经验: 15, 金币: 6 * 4 } },
      { 类型: '收获', 作物: '小麦', 数量: 2, 奖励: { 经验: 15, 金币: 4 * 4 } },
      { 类型: '销售', 作物: '小麦', 数量: 5, 奖励: { 经验: 8, 金币: 10 * 4 } },
      { 类型: '销售', 作物: '胡萝卜', 数量: 5, 奖励: { 经验: 8, 金币: 15 * 4 } },
      { 类型: '销售', 作物: '土豆', 数量: 5, 奖励: { 经验: 8, 金币: 12 * 4 } }
    ];
    
    // 随机选择2个任务
    for (let i = 0; i < 2; i++) {
      const 随机任务 = 任务类型[Math.floor(Math.random() * 任务类型.length)];
      Game.状态.农场数据.任务.push({
        ...随机任务,
        id: Date.now() + i,
        进度: 0,
        完成: false
      });
    }
  }

  function 检查任务完成(任务类型, 作物, 数量 = 1) {
    Game.状态.农场数据.任务.forEach(任务 => {
      if (!任务.完成 && 任务.类型 === 任务类型 && 任务.作物 === 作物) {
        任务.进度 += 数量;
        
        if (任务.进度 >= 任务.数量) {
          任务.完成 = true;
          Game.状态.农场数据.经验值 += 任务.奖励.经验;
          Game.状态.钱 += 任务.奖励.金币;
          Game.消息队列添加(`完成任务：${任务.类型}${任务.作物}！获得经验${任务.奖励.经验}，金币${任务.奖励.金币}`, "任务完成");
          
          // 更新经验值显示
          更新状态显示();
        }
      }
    });
  }

