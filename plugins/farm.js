  // 时间转换函数：将游戏时间转换为总小时数
  function 时间到总小时数(时间) {
    // 每季度3天，每天24小时
    const 季度小时数 = (时间.季 - 1) * 3 * 24;
    const 天小时数 = (时间.日 - 1) * 24;
    return 季度小时数 + 天小时数 + 时间.时;
  }
  
  // 总小时数到时间的转换
  function 总小时数到时间(总小时数) {
    const 时间 = {
      年: 1,
      季: 1,
      日: 1,
      时: 6
    };
    
    // 每季度72小时（3天×24小时）
    const 总季度数 = Math.floor(总小时数 / 72);
    时间.季 = (总季度数 % 4) + 1;
    
    // 计算年份
    时间.年 = Math.floor(总季度数 / 4) + 1;
    
    // 剩余小时数
    let 剩余小时数 = 总小时数 % 72;
    
    // 天数
    时间.日 = Math.floor(剩余小时数 / 24) + 1;
    
    // 小时
    时间.时 = 剩余小时数 % 24;
    
    return 时间;
  }

